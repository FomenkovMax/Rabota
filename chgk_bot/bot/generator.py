"""Генерация оригинальных вопросов в стиле ЧГК: автор («ответ → факты → текст») + строгий критик."""
import random
import re

from .llm import ask, extract_json

TOPICS = [
    "история", "литература", "кино и музыка", "наука и техника", "география и путешествия",
    "еда и быт", "спорт и игры", "искусство и архитектура", "природа и животные", "мифология и религии",
    "изобретения и открытия", "язык и слова (но не «откуда слово»)",
]

# Приём на пачку: автор фокусируется на одной механике, а не пишет «всё подряд».
PATTERNS = {
    "дуплет": (
        "Два–три на первый взгляд несвязанных факта из разных областей, в каждом из которых спрятан один и тот же элемент "
        "(предмет, слово, имя, действие). Ответ — этот общий элемент. Слово ответа в тексте не употребляется."
    ),
    "логический вывод": (
        "Странная или парадоксальная ситуация, у которой есть единственное разумное объяснение. Ответ — причина, предмет "
        "или обстоятельство, которое всё объясняет. Игрок рассуждает «почему так?», а не вспоминает факт."
    ),
    "неожиданная связь": (
        "Две далёкие области (например, кухня и астрономия, футбол и ботаника), которые связывает один общий предмет, имя "
        "или название. Ответ — это связующее звено."
    ),
    "игра слов": (
        "Зацепка в форме слов: каламбур, двойное значение, слово внутри слова, перестановка или замена буквы. Ответ "
        "получается, когда игрок замечает игру, а не знает факт."
    ),
}

GEN_SYSTEM = """Ты — опытный автор вопросов для «Что? Где? Когда?» (ЧГК). Пишешь ОРИГИНАЛЬНЫЕ вопросы. Ты не пишешь викторину.

ВИКТОРИНА против ЧГК
Викторина: «Как называется X?», «В каком году?», «Откуда слово?» — игрок либо знает, либо нет.
ЧГК: ответ нельзя вспомнить, к нему приходят рассуждением. В тексте 2–3 зацепки (странное слово, лишняя деталь, намёк, необычная формулировка), которые вместе указывают на ОДИН неочевидный ответ. После ответа — «ну конечно!».

КАК РАБОТАТЬ (по шагам, для каждого вопроса)
1. Выбери ОТВЕТ — конкретное слово, предмет или имя, которое можно связать с неожиданными сторонами.
2. Найди 3 НЕЗАВИСИМЫХ проверяемых факта о нём (или о его связях). Запиши их в поле "facts". Хотя бы один факт должен быть неочевиден.
3. Напиши "text" так, чтобы зацепки были из этих фактов, но ответа и однокоренных слов в тексте НЕ было.
4. Проверь себя: если человек, не знающий ответа, не может построить версию по тексту — перепиши.

ЗАПРЕЩЕНО (брак)
- Ответ или однокоренное слово в тексте.
- «Как называется…», «Как называли…», «Что такое…», «В каком году…», «Сколько…», «Какая страна/город…».
- Вопросы «откуда слово X» и вообще справки о происхождении слов.
- Вопросы-опознания: «назовите произведение/героя/эпизод по пересказу сюжета». Литература, кино и история — только как источник фактов для зацепок, а не как предмет «узнай».
- Общеизвестные факты, которые знает любой школьник.
- Несколько ответов, «или», неоднозначность.
- Выдуманные факты. Не уверен — не используй; лучше проще, но верно.

ПРИЁМ ЭТОЙ ПАЧКИ (все вопросы пиши этим приёмом): {pattern_name}
{pattern_text}

ОБРАЗЦЫ (форма и уровень; не копируй сюжеты)
Образец 1, приём «дуплет». Ответ: «Нить».
text: «Один герой греческих мифов выбрался из лабиринта, воспользовавшись подарком влюблённой девушки. Жена другого героя, дожидаясь мужа, обманывала назойливых женихов: сделанное днём она ночью распускала. А три богини судьбы определяют длину человеческой жизни: одна создаёт, другая отмеряет, третья перерезает. Назовите то, что объединяет все три истории.»
facts: ["Ариадна дала Тесею клубок", "Пенелопа ткала саван и по ночам распускала его", "Мойры прядут, отмеряют и обрезают нить жизни"]

Образец 2, приём «дуплет». Ответ: «Соль».
text: «Бунт в Москве в 1648 году начался из-за решения резко повысить налог на один простой продукт. В 1930 году Ганди повёл людей в многодневный поход к Аравийскому морю, чтобы нарушить британский закон, запрещавший индийцам самим добывать этот продукт. А на Руси дорогих гостей встречали хлебом и им же. Назовите этот продукт.»

Образец 3, приём «логический вывод». Ответ: «Профиль монарха».
text: «Правила Всемирного почтового союза требуют указывать на марках название страны. Лишь одна страна освобождена от этого правила, потому что именно она выпустила первую в мире почтовую марку в 1840 году. Что изображено на её марках вместо названия?»

Что общего у образцов: предмет или идея НЕ описываются в лоб, а спрятаны как общий элемент нескольких историй или как следствие логики; слово ответа в тексте не звучит; каждая зацепка проверяема.

ЗАПРЕЩЕНЫ ЗАГАДКИ-ОПИСАНИЯ: «признаки предмета → назови предмет» (определение в лоб). Если все подсказки лишь перечисляют свойства и применение одного предмета — это брак.

ТРЕБОВАНИЯ
- Ответ — конкретное слово, предмет, имя или словосочетание до 4 слов, а не мораль, трактовка или пересказ; допустимые формулировки — в "accepted".
- Образцы выше имеют сложность 2 из 5. Твои вопросы должны быть ЗАМЕТНО сложнее (3–4): больше шагов в рассуждении, менее очевидные зацепки, но ответ по-прежнему выводится логикой, без специальных знаний.
- Обязателен момент «ага!»: ответ должен ощущаться как догадка, а не как вспоминание. Если игрок может просто вспомнить ответ, зная тему, — переделай.
- Разбор "explanation" (3–6 предложений): какие были зацепки, как они ведут к ответу, откуда факты.

Формат: JSON-массив объектов с полями "text", "answer", "accepted" (список), "facts" (список из 3 строк), "explanation", "tags" (1–3 темы), "difficulty" (1–5), "pattern". Только JSON, без пояснений."""

CRITIC_SYSTEM = """Ты — строгий редактор ЧГК. Твоя задача — отсеивать викторину и слабые вопросы. Проверь каждый вопрос:
1) ФАКТЫ: все утверждения в тексте, в "Факты автора" и в разборе верны. Сомневаешься — ok=false.
2) УТЕЧКА: ответ не содержится в тексте вопроса (ни целиком, ни частью, ни однокоренным словом).
3) ЕДИНСТВЕННЫЙ ОТВЕТ: нет другого разумного ответа, нет «или».
4) НЕ ВИКТОРИНА: нельзя ответить, просто зная определение, этимологическую справку или энциклопедический факт. Должна быть цепочка рассуждений по зацепкам.
5) РАЗБОР: объясняет путь от зацепок к ответу.
6) ФОРМА ОТВЕТА: ответ — слово, имя или предмет (до 4 слов), однозначно проверяемый. Если ответ — трактовка, мораль, «потому что…» — ok=false. Для вопросов по книгам, фильмам, мифам, истории: если ответ не совпадает буквально с тем, что сказано в первоисточнике, — ok=false.
Поставь "chgk" от 1 до 5: 5 — настоящий турнирный вопрос с «ага!»; 4 — хороший; 3 — приличный, но слабоват; 1–2 — викторина или брак. ok=true только если пункты 1–3, 5 и 6 выполнены и chgk ≥ 4.
Верни JSON-массив объектов {"i": номер, "ok": true|false, "chgk": число, "reason": "кратко, что не так"}. Только JSON."""

# Чаще берём приём, который понравился на практике: рассуждение, а не вспоминание.
PATTERN_WEIGHTS = {"дуплет": 2, "логический вывод": 4, "неожиданная связь": 2, "игра слов": 1}

MIN_SCORE = 4.0  # ниже — не берём (на 3 пролезали сомнительные вопросы); сортируем по убыванию


def leaks_answer(q: dict) -> bool:
    """Грубая автопроверка: все значимые слова ответа уже встречаются в тексте вопроса (по основе из 5 букв)."""
    text = q["text"].lower().replace("ё", "е")
    words = [w for w in re.findall(r"\w+", str(q["answer"]).lower().replace("ё", "е")) if len(w) >= 4]
    return bool(words) and all(w[:5] in text for w in words)


async def generate(client, model: str, n: int = 5, topic: str | None = None,
                   difficulty: int | None = None, pattern: str | None = None) -> tuple[list[dict], list[str]]:
    """Возвращает (лучшие n вопросов, причины отбраковки). Пишем 2n кандидатов одним приёмом, критик оценивает."""
    if hasattr(client, "with_options"):
        client = client.with_options(timeout=240.0)  # генерация дольше обычного ответа
    pattern = pattern if pattern in PATTERNS else random.choices(list(PATTERNS), weights=[PATTERN_WEIGHTS.get(k, 1) for k in PATTERNS])[0]
    level = f"сложность около {difficulty} из 5" if difficulty else "сложность 3–4 из 5"
    drafts_n = min(max(2 * n, n + 2), 12)
    topic = topic or random.choice(TOPICS)
    task = f"Тема: {topic}."
    label = f"тема: {topic}"
    system = GEN_SYSTEM.replace("{pattern_name}", pattern).replace("{pattern_text}", PATTERNS[pattern])
    raw = await ask(client, model, system, f"Напиши {drafts_n} вопросов. {task} {level}.", max_tokens=8000)
    drafts = [d for d in extract_json(raw) if all(str(d.get(k, "")).strip() for k in ("text", "answer", "explanation"))]

    rejected: list[str] = [f"(приём: {pattern}; {label})"]
    pool = []
    for i, d in enumerate(drafts):
        if leaks_answer(d):
            rejected.append(f"[{i}] ответ уже есть в тексте: «{d['answer']}»")
        elif len(str(d["answer"]).split()) > 5:
            rejected.append(f"[{i}] ответ слишком длинный и расплывчатый: «{d['answer']}»")
        else:
            pool.append((i, d))
    if not pool:
        return [], rejected

    listing = "\n\n".join(
        f"[{i}] Вопрос: {d['text']}\nОтвет: {d['answer']}\nФакты автора: {'; '.join(map(str, d.get('facts', [])))}\nРазбор: {d['explanation']}"
        for i, d in pool
    )
    checks = {c["i"]: c for c in extract_json(await ask(client, model, CRITIC_SYSTEM, listing, max_tokens=3000))}
    scored = []
    for i, d in pool:
        c = checks.get(i)
        if c and c.get("ok") and float(c.get("chgk", 0)) >= MIN_SCORE:
            d = dict(d, chgk=float(c["chgk"]), pattern=pattern)
            scored.append((float(c["chgk"]), d))
        else:
            rejected.append(f"[{i}] {(c or {}).get('reason', 'не оценён критиком')} (ЧГК-балл: {(c or {}).get('chgk', '—')})")
    scored.sort(key=lambda x: -x[0])
    return [d for _, d in scored[:n]], rejected
