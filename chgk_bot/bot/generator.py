"""Генерация оригинальных вопросов в стиле ЧГК: автор + критик."""
import random

from .llm import ask, extract_json

TOPICS = [
    "слова и этимология", "история", "литература", "кино и музыка", "наука и техника",
    "география", "еда и быт", "спорт и игры", "искусство", "язык и неожиданные совпадения",
]

GEN_SYSTEM = """Ты — опытный редактор вопросов для «Что? Где? Когда?» (ЧГК). Пишешь ОРИГИНАЛЬНЫЕ вопросы.

Главное в хорошем вопросе ЧГК:
- Ответ нельзя просто знать или загуглить: к нему приходят логикой, из «зацепок» в тексте. Энциклопедическая эрудиция не должна быть решающей.
- В тексте есть 2–3 зацепки (необычное слово, намёк, странная формулировка), которые вместе указывают на единственный ответ.
- Ответ один, короткий (слово или словосочетание) и однозначный. Нет вариантов «или».
- Формулировка внимательно подобрана: каждое слово работает. Лишнего нет.
- «Прозрение»: после ответа игрок говорит «ну конечно!».
- Все факты должны быть настоящими и проверяемыми. Если не уверен в факте — не используй его. Не придумывай цитаты, даты и имена.
- Не копируй известные вопросы из турниров и баз; придумай свой.

Формат: JSON-массив объектов с полями:
"text" (текст вопроса, 2–5 предложений), "answer" (эталонный ответ),
"accepted" (список допустимых вариантов формулировки ответа, может быть пустым),
"explanation" (разбор: пошагово как от зацепок прийти к ответу, 3–6 предложений),
"tags" (1–3 темы), "difficulty" (1–5).
Только JSON, без пояснений."""

CRITIC_SYSTEM = """Ты — придирчивый редактор-проверяющий вопросов ЧГК. Для каждого вопроса проверь:
1) все фактические утверждения в тексте и разборе верны;
2) ответ единственный и однозначный (нет другого разумного ответа);
3) к ответу можно прийти логикой по зацепкам, а не только знанием энциклопедии;
4) разбор действительно объясняет путь к ответу.
Верни JSON-массив из объектов {"i": номер, "ok": true|false, "reason": "кратко"}. Ставь ok=true только если уверен во всём. Только JSON."""


async def generate(client, model: str, n: int = 5, topic: str | None = None,
                   difficulty: int | None = None) -> tuple[list[dict], list[str]]:
    """Возвращает (прошедшие проверку вопросы, причины отбраковки)."""
    topic = topic or random.choice(TOPICS)
    level = f"сложность около {difficulty} из 5" if difficulty else "разная сложность (2–4 из 5)"
    raw = await ask(client, model, GEN_SYSTEM, f"Напиши {n} вопросов. Тема: {topic}. {level}.", max_tokens=6000)
    drafts = extract_json(raw)
    listing = "\n\n".join(
        f"[{i}] Вопрос: {d['text']}\nОтвет: {d['answer']}\nРазбор: {d['explanation']}"
        for i, d in enumerate(drafts)
    )
    checks = extract_json(await ask(client, model, CRITIC_SYSTEM, listing, max_tokens=2000))
    ok_idx = {c["i"] for c in checks if c.get("ok")}
    rejected = [f"[{c['i']}] {c.get('reason', '')}" for c in checks if not c.get("ok")]
    return [d for i, d in enumerate(drafts) if i in ok_idx], rejected
