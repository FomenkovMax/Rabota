"""Генерация оригинальных вопросов в стиле ЧГК: автор + критик."""
import random
import re

from .llm import ask, extract_json

TOPICS = [
    "слова и этимология", "история", "литература", "кино и музыка", "наука и техника",
    "география", "еда и быт", "спорт и игры", "искусство", "язык и неожиданные совпадения",
]

GEN_SYSTEM = """Ты — опытный редактор вопросов для «Что? Где? Когда?» (ЧГК). Пишешь ОРИГИНАЛЬНЫЕ вопросы, которые отличаются от обычной викторины.

ГЛАВНОЕ ОТЛИЧИЕ ЧГК ОТ ВИКТОРИНЫ
Викторина: «Как называется X?», «В каком году?», «Какую страну?» — игрок либо знает, либо нет.
ЧГК: ответ нельзя просто вспомнить, к нему приходят рассуждением. В тексте есть 2–3 зацепки (странное слово, необычная формулировка, лишняя деталь, намёк), которые вместе указывают на ОДИН неочевидный ответ. После ответа игрок говорит «ну конечно!».

ЗАПРЕЩЕНО (такой вопрос — брак):
- Ответ содержится в тексте вопроса: целиком, частью или однокоренным словом (нельзя «облагали налогом окна… Как назывался налог?»).
- Вопросы-определения: «Как называется…», «Как называли…», «Что такое…».
- Вопросы на число, год, дату, столицу, страну, фамилию по общеизвестному описанию.
- Ответ, который можно угадать, не вникая в текст, или который знает любой школьник.
- Несколько равноправных ответов; «или»; неоднозначность.

ПРИЁМЫ ЧГК (используй разные):
1. «Дуплет»: два–три на первый взгляд несвязанных факта, в которых спрятан общий элемент (слово, имя, предмет). Ответ — этот элемент.
2. «Замена»: в тексте слово заменено на «ЭТО» или «он/она»; по описаниям и намёкам нужно восстановить заменённое.
3. «Этимология с поворотом»: известное слово/название, происхождение которого связано с неожиданным фактом; ответ получается из рассуждения о происхождении, а не из определения.
4. «Логический вывод»: из странного описания ситуации следует единственное объяснение; ответ — причина или предмет, а не пересказ.
5. «Игра слов»: каламбур, двойное значение, перестановка букв, слово внутри слова — зацепка в самой форме слов.
6. «Неожиданная связь»: две области (например, кухня и астрономия), общий предмет или имя.

ТРЕБОВАНИЯ
- Ответ короткий (слово или словосочетание), однозначный. Допустимые варианты формулировки — в "accepted".
- Каждое слово в тексте работает; лишнего нет. Зацепки не должны быть «в лоб».
- Сложность 3–4 из 5: человек без специальных знаний, но внимательный и сообразительный, может додуматься за минуту.
- Все факты настоящие и проверяемые. Если не уверен в факте, дате, имени или цитате — не используй. Лучше проще, но верно.
- Не копируй известные вопросы из турниров и баз; придумай свой.
- В "explanation" (3–6 предложений) разбери по шагам: какие зацепки были, как они ведут к ответу, откуда берутся факты.

Формат: JSON-массив объектов с полями:
"text" (2–5 предложений), "answer", "accepted" (список, может быть пустым),
"explanation", "tags" (1–3 темы), "difficulty" (1–5), "pattern" (номер или название приёма).
Только JSON, без пояснений."""

CRITIC_SYSTEM = """Ты — строгий редактор ЧГК. Твоя задача — отсеивать викторину и слабые вопросы. Проверь каждый вопрос:
1) ФАКТЫ: все утверждения в тексте и в разборе верны. Сомневаешься — ok=false.
2) УТЕЧКА: ответ не содержится в тексте вопроса (ни целиком, ни частью, ни однокоренным словом).
3) ЕДИНСТВЕННЫЙ ОТВЕТ: нет другого разумного ответа, нет «или».
4) НЕ ВИКТОРИНА: нельзя ответить, просто зная определение или энциклопедический факт («как называется…», «в каком году…», «какая страна…»). Должна быть цепочка рассуждений по зацепкам.
5) РАЗБОР: объясняет путь от зацепок к ответу.
Поставь "chgk" от 1 до 5: 5 — настоящий турнирный вопрос с «ага!»; 3 — приличный, но слабый; 1–2 — викторина. ok=true только если пункты 1–5 выполнены и chgk ≥ 4.
Верни JSON-массив объектов {"i": номер, "ok": true|false, "chgk": число, "reason": "кратко, что не так"}. Только JSON."""


def leaks_answer(q: dict) -> bool:
    """Грубая автопроверка: все значимые слова ответа уже встречаются в тексте вопроса (по основе из 5 букв)."""
    text = q["text"].lower().replace("ё", "е")
    words = [w for w in re.findall(r"\w+", str(q["answer"]).lower().replace("ё", "е")) if len(w) >= 4]
    return bool(words) and all(w[:5] in text for w in words)


async def generate(client, model: str, n: int = 5, topic: str | None = None,
                   difficulty: int | None = None) -> tuple[list[dict], list[str]]:
    """Возвращает (лучшие n вопросов, причины отбраковки). Пишем 2n кандидатов, критик оценивает, берём лучших."""
    if hasattr(client, "with_options"):
        client = client.with_options(timeout=240.0)  # генерация дольше обычного ответа
    topic = topic or random.choice(TOPICS)
    level = f"сложность около {difficulty} из 5" if difficulty else "сложность 3–4 из 5"
    drafts_n = min(max(2 * n, n + 2), 12)
    raw = await ask(client, model, GEN_SYSTEM, f"Напиши {drafts_n} вопросов. Тема: {topic}. {level}. Используй разные приёмы.", max_tokens=8000)
    drafts = [d for d in extract_json(raw) if all(str(d.get(k, "")).strip() for k in ("text", "answer", "explanation"))]

    rejected: list[str] = []
    pool = []
    for i, d in enumerate(drafts):
        if leaks_answer(d):
            rejected.append(f"[{i}] ответ уже есть в тексте: «{d['answer']}»")
        else:
            pool.append((i, d))
    if not pool:
        return [], rejected

    listing = "\n\n".join(
        f"[{i}] Вопрос: {d['text']}\nОтвет: {d['answer']}\nРазбор: {d['explanation']}" for i, d in pool
    )
    checks = {c["i"]: c for c in extract_json(await ask(client, model, CRITIC_SYSTEM, listing, max_tokens=3000))}
    scored = []
    for i, d in pool:
        c = checks.get(i)
        if c and c.get("ok") and float(c.get("chgk", 0)) >= 4:
            scored.append((float(c["chgk"]), d))
        else:
            rejected.append(f"[{i}] {(c or {}).get('reason', 'не оценён критиком')} (ЧГК-балл: {(c or {}).get('chgk', '—')})")
    scored.sort(key=lambda x: -x[0])
    return [d for _, d in scored[:n]], rejected
